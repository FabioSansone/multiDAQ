def _add_common_acquisition_arguments(parser: argparse.ArgumentParser) -> None:
    """
    Add arguments shared by all acquisition trigger modes.
    """

    parser.add_argument(
        "--duration",
        type=float,
        default=None,
        help=(
            "Acquisition duration in seconds. "
            "If omitted, run until stopped."
        ),
    )

    parser.add_argument(
        "--type",
        dest="acq_type",
        type=str,
        default="test",
        help=(
            "Acquisition type, e.g. test, pedestal, spe, gain, threshold."
        ),
    )

    parser.add_argument(
        "--suffix",
        type=str,
        default="",
        help="Suffix for the output file name.",
    )

    parser.add_argument(
        "--run-id",
        type=str,
        default=None,
        help=(
            "Optional run ID. "
            "If omitted, an automatic acq_N folder is created."
        ),
    )

    parser.add_argument(
        "--file-format",
        type=str,
        choices=["csv", "bin"],
        default="csv",
        help="Output file format. Default: csv.",
    )


