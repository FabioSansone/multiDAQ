###################
# FSM PER COMMAND #
###################

COMMAND_FSM_MAP = {
    "start": {ServerFSM.READY},
    "stop": {
        ServerFSM.ACQUIRING,
        ServerFSM.FINALIZING,
        ServerFSM.READY,
    },
}


@cmd2.with_argparser(acquisition_parser)
@cmd2.with_category("Acquisition Commands")
@command_guard(
    [
        ServerFSM.READY,
        ServerFSM.ACQUIRING,
        ServerFSM.FINALIZING,
    ]
)
def do_acquisition(self, args: argparse.Namespace) -> None:
    """
    Acquisition commands:
        acquisition start self
        acquisition start external
        acquisition start auto majority
        acquisition start auto exact
        acquisition stop
    """

    current_state = self.server_state.get_server_state()
    allowed_states = COMMAND_FSM_MAP[args.command]

    if current_state not in allowed_states:
        allowed_names = ", ".join(
            sorted(state.value for state in allowed_states)
        )

        self.poutput(
            f"Cannot run 'acquisition {args.command}' while server is "
            f"'{current_state.value}'. Allowed states: {allowed_names}."
        )

        logger.error(
            f"Acquisition command '{args.command}' blocked: "
            f"state={current_state.value}"
        )
        return

    if args.command == "start":
        self.acquisition_orchestrator.start(args)
        return

    if args.command == "stop":
        self.acquisition_orchestrator.stop()
        return

